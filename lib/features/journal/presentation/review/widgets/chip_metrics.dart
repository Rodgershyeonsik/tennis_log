/// 태그 확인 화면의 칩·버튼이 함께 쓰는 치수.
///
/// 태그 칩, `＋` 칩, 평가 버튼이 한 카드 안에 나란히 놓이므로 **둥근 정도와
/// 높이를 한곳에서만 정한다.** 각자 안쪽 여백으로 높이를 만들면 글자와 아이콘
/// 크기 차이 때문에 몇 px씩 어긋나 보인다(실제로 태그 칩 36, `＋` 칩 32로
/// 벌어져 있었다).
abstract final class ChipMetrics {
  /// 모서리를 깎는 정도. 테마의 `chipTheme`과 같은 값이다.
  static const radius = 10.0;

  /// 태그 칩과 `＋ 태그 추가` 칩이 함께 쓰는 높이.
  ///
  /// 고정 높이가 아니라 **최소**인 이유는 기기 글자 크기를 키웠을 때 글자가
  /// 잘리지 않게 하려는 것이다. 보통은 두 칩이 이 값으로 맞춰진다.
  static const minHeight = 36.0;

  /// 평가 버튼의 보이는 크기. **높이보다 넓다.**
  ///
  /// 아이콘을 정사각형 안에 넣으면 위아래 여백이 좌우와 같아져서 버튼이
  /// 뭉툭하게 솟아 보인다. 좌우를 더 벌려 가로형으로 둔다.
  ///
  /// 칩([minHeight])보다 조금 높은 건 그렇게 보도록 고른 값이다 — 칩은 글자가
  /// 안을 채우지만 평가 버튼은 아이콘 하나뿐이라, 높이를 똑같이 맞추면 오히려
  /// 작아 보인다.
  static const evaluationWidth = 46.0;
  static const evaluationHeight = 40.0;

  /// 손가락이 닿아야 하는 최소 크기(CLAUDE.md).
  ///
  /// 평가 버튼은 **보이는 크기보다 이쪽을 크게** 잡는다.
  static const touchSize = 48.0;
}
